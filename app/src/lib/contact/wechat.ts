/**
 * WeChat（微信）のサポート窓口。会員 → スタッフの主要な連絡導線。
 *
 * ⚠️ **QRコードを自前で生成してはいけない。**
 * WeChatの「友だち追加」QRは、WeChat IDの文字列をQRにエンコードしたものではなく、
 * アカウントごとにWeChatが発行する `http://weixin.qq.com/r/…` 形式のデータを持つ。
 * IDからは計算できないため、`WECHAT_ID` を正しくQRエンコードしても、
 * WeChatで読み取ったときに「ただの文字列」として表示されるだけで友だち追加にならない。
 *
 * したがってQRを出す唯一の正しい方法は、**オーナーがWeChatアプリから書き出した公式の画像**
 * （「我」→「二维码名片」→ 画像を保存）を `app/public/` に置き、そのパスを
 * `WECHAT_QR_SRC` に設定すること。
 *
 * 画像がある場合の利点: WeChatの内蔵ブラウザでは `<img>` のビットマップに対して
 * 「长按识别二维码」（長押しで読み取り）が効く。微信群・朋友圈からの流入では
 * これが最短の導線になる。※インラインSVGでは効かないので必ず画像で置くこと。
 */

/** 公式サポートのWeChat ID。変更するときはここだけを直す。 */
export const WECHAT_ID = "yingpin-support";

/**
 * 公式QR画像のパス（`app/public/` からの絶対パス。例: `"/wechat-qr.png"`）。
 * `null` のあいだはQRを表示せず、ID＋検索手順の案内だけを出す。
 * 画像を置いたらこの1行を変えるだけでQR表示に切り替わる。
 */
export const WECHAT_QR_SRC: string | null = null;
